export type RunPlan = {
  format: 'operon.run-plan'; schema_version: 1; plan_id: string; workflow_revision: string;
  parameters_digest: string; compiler_version: string;
  units: {unit_id: string; node_ids: string[]; invocation: {environment_ref: string | null; kind: string};
    input_bindings: Record<string, string>; placement: {executor: string; target: {os: string; arch: string}};
    resource_request: {cpu_threads: number; process_reservation_bytes: number};
    output_contracts: {name: string; representation: string}[]}[];
  storage_bindings: {storage_id: string; relative_path: string}[];
  environment_requirements: {runtime: string; target: {os: string; arch: string}}[];
  [key: string]: unknown;
};
export type BoundEnvironment = {generation_id: string; executable: string};
export type BoundInput = {representation: 'form' | 'file' | 'table' | 'json' | 'npy' | 'report' | 'figure';
  path: string; sha256: string; size_bytes: number; metadata: Record<string, unknown>};
export type PlanBinding = {package_root: string; environment_store: string;
  environments: Record<string, BoundEnvironment>; storage: Record<string, string>; inputs: Record<string, BoundInput>};
export type PlanSubmission = {plan: RunPlan; binding: PlanBinding; request_id: string};
export type PlanCompile = {kind?: 'graph' | 'authoring-v2'; workflow: Record<string, unknown>;
  directory?: string; values?: unknown; parameters?: Record<string, unknown>; inputs?: Record<string, unknown>;
  environments?: Record<string, unknown>; initial?: boolean; profile?: string; require_files?: boolean};
export type PlanRecord = {title: string; created_at: string; submission: PlanSubmission;
  run_id?: string | null; status: 'pending' | 'unknown' | 'accepted' | 'rejected'};
export type PlanExportRequest = {plan: RunPlan; request_id: string; source_root: string;
  environment_store: string; output: string; environments: Record<string, BoundEnvironment>;
  implementations?: Record<string, unknown>; extra_files?: Record<string, unknown>; management_environment?: string | null;
  input_bindings?: Record<string, string>; input_formats?: Record<string, string>};
export type PlanUiState = {version: 1; revision: number; records: PlanRecord[];
  exports: {request: PlanExportRequest; export_id?: string | null}[]};
export type PlanReceipt = {run_id: string; state: string; revision?: number; unit_count?: number; attempt_count?: number; results?: string};
export type PlanEvent = {cursor: number; kind: string; unit_id?: string; attempt_id?: string; created_at: string};
export type PlanAttempt = {attempt_id: string; unit_id: string; ordinal: number; state: string; exit_code?: number | null; error_code?: string | null};
export type PlanArtifact = {artifact_id: string; unit_id: string; attempt_id: string; sha256: string; size_bytes: number; reused: number | boolean};
export type PlanPage<T, K extends string> = {run_id: string; revision: number; next_cursor: string; has_more: boolean} & Record<K, T[]>;
export type PlanEvents = Omit<PlanPage<PlanEvent, 'events'>, 'next_cursor'> & {next_cursor: number; floor: number};
export type PlanLog = {available: boolean; data: string; next_offset: number; eof: boolean; bytes_read: number};
export type PlanFile = {file_id: string; name: string; size_bytes: number; media_type: string; sha256: string};
export type PlanFilePreview = {kind: 'text' | 'binary'; content: string | null; truncated: boolean; bytes_read: number; digest_verified: boolean};
export type ExportReceipt = {id: string; request_id: string; plan_id: string; status: string; phase: string; output: string; error?: unknown};
export type BindingOptions = {package_root: string; environment_store: string;
  environments: Record<string, (BoundEnvironment & {label?: string; verified?: boolean})[]>;
  storage: Record<string, string>; inputs: Record<string, BoundInput>; missing?: string[]};
